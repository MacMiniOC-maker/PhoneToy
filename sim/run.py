#!/usr/bin/env python3
"""Run every PhoneToy circuit simulation and print the results as Markdown tables.

Needs ngspice on PATH.   python3 sim/run.py > sim/RESULTS.md
The .cir files also open directly in LTspice and in KiCad's simulator.
"""
import os, re, subprocess, sys, tempfile

HERE = os.path.dirname(os.path.abspath(__file__))

def run(name, **params):
    """Run one netlist with .param overrides; return {measurement: value}."""
    text = open(os.path.join(HERE, name)).read()
    for k, v in params.items():
        text, n = re.subn(rf"(?m)^\.param {k}=\S+", f".param {k}={v}", text)
        assert n == 1, f"{name}: no .param {k}"
    with tempfile.NamedTemporaryFile("w", suffix=".cir", delete=False) as f:
        f.write(text)
    try:
        out = subprocess.run(["ngspice", "-b", f.name], capture_output=True, text=True, timeout=120).stdout
    finally:
        os.unlink(f.name)
    vals = {}
    for m in re.finditer(r"(?m)^\s*([a-z_]+(?:\([a-z0-9_]+\))?)\s*=\s*(-?[\d.]+e[-+]\d+)", out):
        vals[m.group(1)] = float(m.group(2))
    if not vals:
        sys.exit(f"{name}: no results\n{out[-800:]}")
    return vals

def led_rows():
    print("## 1. Button light driver (`led_driver.cir`)\n")
    print("GPIO at 3.3 V, 1 kΩ base resistor, 2N2222, blue/white LED on the 5 V rail. "
          "The resistor inside the button is unknown until you measure it, so it is swept.\n")
    print("| Resistor in the LED path | LED current | From the GPIO pin | "
          "Transistor drop | Transistor heat | Same LED straight off a GPIO |")
    print("|---|---|---|---|---|---|")
    for r in (1000, 470, 330, 220, 150, 1):
        d = run("led_driver.cir", RLED=r)
        direct = run("led_direct.cir", RLED=r)
        iled, ig, vce = -d["i(v5)"], -d["i(vg)"], d["v(coll)"]
        label = "none (bare LED)" if r == 1 else f"{r} Ω"
        print(f"| {label} | {iled*1e3:.1f} mA | {ig*1e3:.2f} mA | {vce*1e3:.0f} mV | "
              f"{vce*iled*1e3:.1f} mW | {-direct['i(vg)']*1e3:.2f} mA |")
    p = run("led_pwm.cir")
    print(f"\nSwitching at the firmware's 1 kHz dimming rate: on in {p['t_on']*1e9:.0f} ns, "
          f"off in {p['t_off']*1e9:.0f} ns, against a 1,000,000 ns period.\n")
    return -run('led_driver.cir', RLED=150)['i(v5)'] * 1e3

def cable_rows():
    print("## 2. I2S clock down the handset cable (`i2s_cable.cir`)\n")
    print("1.024 MHz bit clock, 3.3 V, 2 ns edges, into the mic's clock pin. "
          "The mic's absolute limits are −0.3 V and 3.6 V (VDD + 0.3 V).\n")
    print("| Cable | Series resistor at the ESP32 | Highest voltage at the mic | Lowest voltage at the mic | Within limits |")
    print("|---|---|---|---|---|")
    for length, name in ((0.1, "10 cm (on the breadboard)"), (0.3, "30 cm (12 in handset cord)"), (1.5, "1.5 m (long coiled cord)")):
        for rs in (0, 33, 68, 100):
            d = run("i2s_cable.cir", LEN=length, RSER=rs)
            ok = d["vmax"] <= 3.6 and d["vmin"] >= -0.3
            print(f"| {name} | {rs} Ω | {d['vmax']:.2f} V | {d['vmin']:.2f} V | {'yes' if ok else '**no**'} |")
    print()

def power_rows(led_ma):
    print("## 3. USB power budget (arithmetic, not simulation)\n")
    print("Typical datasheet figures and estimates. The LED figure is the 150 Ω row above, the brightest plausible case.\n")
    rows = [("ESP32-S3 with Wi-Fi", 100, 340), ("Four button lights", 4 * led_ma, 4 * led_ma),
            ("Ringer amplifier while ringing (about 0.25 W into 4 Ω)", 55, 55),
            ("Earpiece amplifier, microphone, idle draw", 8, 8)]
    print("| Load | Typical | Peak |")
    print("|---|---|---|")
    for name, typ, peak in rows: print(f"| {name} | {typ:.0f} mA | {peak:.0f} mA |")
    t, pk = sum(r[1] for r in rows), sum(r[2] for r in rows)
    print(f"| **Total** | **{t:.0f} mA** | **{pk:.0f} mA** |")
    print(f"\nA 5 V 2 A charger has plenty of margin. A computer USB port (500 mA) is fine for bench work, "
          f"with little to spare on Wi-Fi peaks ({pk:.0f} mA).\n")

if __name__ == "__main__":
    print("# Simulation results\n")
    print("Generated by `python3 sim/run.py` with ngspice. These are models, not measurements: "
          "they tell you what to expect and what to check with a multimeter.\n")
    led_ma = led_rows()
    cable_rows()
    power_rows(led_ma)
