#!/usr/bin/env python3
"""Safety audit: every part's worst-case load against its rating, plus fault cases.

    python3 sim/safety.py > sim/SAFETY.md

Ratings are typical datasheet values for these part types. Check them against the
datasheet or listing for the exact parts you bought; the script marks the ones that
are assumptions.
"""
import math, os, re, struct, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from run import run, HERE

cfg = open(os.path.join(HERE, "..", "firmware", "main", "config.h")).read()
def cfgval(name): return int(re.search(rf"#define {name}\s+(\d+)", cfg).group(1))

# ---- ratings (typical; * = assumed, not from your parts' own datasheet) ----
GPIO_MAX_MA   = 20      # conservative design limit per ESP32-S3 pin (absolute max is 40 mA)
Q_IC_MAX_MA   = 600     # 2N2222 collector current
Q_PD_MAX_MW   = 625     # 2N2222 in a TO-92 plastic case, free air
R_PD_MAX_MW   = 250     # quarter-watt resistors
LED_MAX_MA    = 20      # * typical indicator LED
RINGER_MAX_W  = 3.0     # from the shopping list
EAR_MAX_W     = 0.5     # * 28 mm 8 ohm mini speaker, typical lower bound
AMP_VDD_MAX   = 5.5     # MAX98357A
MIC_VDD_MAX   = 3.63    # INMP441
CONTACT_MAX_A = 1.0     # * breadboard contacts and thin jumper wires
USB_PORT_A    = 0.5
CHARGER_A     = 2.0
SENS_DB       = 85      # * small-speaker sensitivity, dB SPL at 1 W / 1 m (unknown for these parts)
AMP_VRMS_MAX  = 3.54    # the most a 5 V bridge amplifier can put out (5 V peak sine)

rows = []
def row(item, value, limit, unit, note="", fixed=False):
    use = value / limit
    # fixed = a regulated supply voltage, where sitting near the limit is normal
    verdict = "**OVER**" if use > 1 else "OK" if (fixed or use <= 0.5) else "OK, little margin"
    rows.append(f"| {item} | {value:.3g} {unit} | {limit:.3g} {unit} | {use*100:.0f}% | {verdict} | {note} |")

def spl(watts, metres): return SENS_DB + 10 * math.log10(max(watts, 1e-9)) - 20 * math.log10(metres)

# ---- normal operation ----
d = run("led_driver.cir", RLED=150)          # brightest plausible built-in resistor
iled, ig, vce = -d["i(v5)"] * 1e3, -d["i(vg)"] * 1e3, d["v(coll)"]
row("GPIO pin driving a transistor", ig, GPIO_MAX_MA, "mA")
row("Transistor current (per light)", iled, Q_IC_MAX_MA, "mA")
row("Transistor heat (per light)", vce * iled, Q_PD_MAX_MW, "mW")
row("1 kΩ base resistor heat", (ig / 1e3) ** 2 * 1000 * 1e3, R_PD_MAX_MW, "mW")
row("Button LED current, 150 Ω built in", iled, LED_MAX_MA, "mA", "depends on the resistor inside your buttons")
row("Amplifier supply voltage", 5.0, AMP_VDD_MAX, "V", "up to 5.25 V from USB is still inside the limit", fixed=True)
row("Microphone supply voltage (on 3V3)", 3.3, MIC_VDD_MAX, "V", "5 V would destroy it", fixed=True)

# ringer: actual tone file x firmware gain
pcm = open(os.path.join(HERE, "..", "firmware", "main", "ring.pcm"), "rb").read()
s = struct.unpack(f"<{len(pcm)//2}h", pcm)
ring_rms_fs = math.sqrt(sum(x * x for x in s) / len(s)) / 32768 * math.sqrt(2)   # relative to a full-scale sine
ring_gain = cfgval("PT_RINGER_GAIN") / 256
ring_w = (AMP_VRMS_MAX * ring_rms_fs * ring_gain) ** 2 / 4
ring_w_max = AMP_VRMS_MAX ** 2 / 4
row("Ringer speaker power, firmware setting", ring_w, RINGER_MAX_W, "W", f"PT_RINGER_GAIN = {cfgval('PT_RINGER_GAIN')}")
ear_gain = cfgval("PT_EARPIECE_GAIN") / 256
ear_r = cfgval("PT_EARPIECE_SERIES_OHMS")
ear_w = (AMP_VRMS_MAX * ear_gain / (ear_r + 8)) ** 2 * 8
row("Earpiece speaker power, loudest possible at firmware setting", ear_w, EAR_MAX_W, "W", f"PT_EARPIECE_GAIN = {cfgval('PT_EARPIECE_GAIN')}, series resistor {ear_r} Ω")
ring_ma = ring_w / 0.9 / 5 * 1e3
typ, peak = 100 + 4 * iled + ring_ma + 8, 340 + 4 * iled + ring_ma + 8
row("Total current, typical", typ / 1e3, USB_PORT_A, "A", "limit shown is a computer USB port")
row("Total current, Wi-Fi peak", peak / 1e3, USB_PORT_A, "A", "limit shown is a computer USB port")
row("Total current, Wi-Fi peak", peak / 1e3, CHARGER_A, "A", "limit shown is the 2 A charger")
row("Current through breadboard contacts", (4 * iled + ring_ma + 8) / 1e3, CONTACT_MAX_A, "A", "everything fed from the 5V pin")
heat_w = 5 * typ / 1e3
box_rise = heat_w / (0.2 * 5)     # ~0.2 m2 of cardboard, ~5 W/m2K to still air

print("# Safety audit\n")
print("Generated by `python3 sim/safety.py`. Every figure is a model or a calculation from typical "
      "datasheet ratings. Nothing here has been measured on your parts.\n")
print("## 1. Normal operation: load against rating\n")
print("| What | Worst-case load | Rating | Used | Verdict | Note |")
print("|---|---|---|---|---|---|")
print("\n".join(rows))
print(f"\nHeat inside the sealed box: about {heat_w:.1f} W in normal use, which warms a shoebox-sized "
      f"cardboard box by roughly {box_rise:.0f} °C. Nothing in normal operation runs hot.\n")

# ---- loudness ----
print("## 2. Loudness\n")
print(f"This is the part that matters most for a toddler. The numbers assume a speaker sensitivity of "
      f"{SENS_DB} dB at 1 W / 1 m, which is a guess for these parts, so treat them as ±10 dB and measure.\n")
print("The WHO safe-listening level for children is 75 dB averaged over time.\n")
print("| Case | Speaker power | Estimated level |")
print("|---|---|---|")
print(f"| Ringer at the firmware setting, 50 cm away | {ring_w*1e3:.0f} mW | {spl(ring_w, .5):.0f} dB |")
print(f"| Ringer if the gain were set to maximum, 50 cm away | {ring_w_max*1e3:.0f} mW | {spl(ring_w_max, .5):.0f} dB |")
print(f"| Earpiece at the firmware setting, loudest possible signal, 5 cm | {ear_w*1e3:.1f} mW | {spl(ear_w, .05):.0f} dB |")
print(f"| Earpiece with no resistor and the gain at maximum, 5 cm | {AMP_VRMS_MAX**2/8*1e3:.0f} mW | {spl(AMP_VRMS_MAX**2/8, .05):.0f} dB |")
print("\nSpeech averages about 20 dB below the loudest possible signal, so everyday levels are well under these.")
print("\nSoftware alone is a weak guard: without a resistor, one wrong number in `config.h` gives the last row. "
      "A resistor in series with the earpiece speaker caps the level in hardware, whatever the software does:\n")
print("| Series resistor | Most power the earpiece can ever get | Estimated level at 5 cm | Heat in the resistor | Resistor OK (¼ W) |")
print("|---|---|---|---|---|")
for r in (0, 47, 100, 220, 470):
    i = AMP_VRMS_MAX / (r + 8)
    p_spk, p_r = i * i * 8, i * i * r
    print(f"| {r} Ω | {p_spk*1e3:.1f} mW | {spl(p_spk, .05):.0f} dB | {p_r*1e3:.0f} mW | "
          f"{'n/a' if r == 0 else 'yes' if p_r <= 0.125 else 'runs warm' if p_r <= 0.25 else 'no'} |")
print()

# ---- faults ----
print("## 3. What happens if something is wired wrong\n")
print("| Mistake | What the model shows | Result | How it is prevented |")
print("|---|---|---|---|")
b = run("led_driver.cir", RLED=1)
print(f"| Button LED has no built-in resistor | {-b['i(v5)']*1e3:.0f} mA through the LED | LED burns out; transistor "
      f"dissipates {b['v(coll)']*-b['i(v5)']*1e3:.0f} mW and survives | Test one LED on 5 V first; add 220 Ω if unsure |")
for rb in ("1k", "2.2k", "4.7k"):
    f = run("fault_collector_short.cir", RB=rb)
    ic, p = -f["i(v5)"], -f["i(v5)"] * f["v(coll)"]
    n = run("led_driver.cir", RB=rb, RLED=150)
    print(f"| Light wire shorts to 5 V, base resistor {rb.replace('k',' kΩ')} | {ic*1e3:.0f} mA, {p:.2f} W in the transistor "
          f"(rating {Q_PD_MAX_MW/1e3:.3g} W) | {'**Transistor overheats**' if p*1e3 > Q_PD_MAX_MW else 'Transistor survives'} | "
          f"Normal operation with this resistor: {-n['i(v5)']*1e3:.1f} mA, {n['v(coll)']*1e3:.0f} mV drop "
          f"({'still fully on' if n['v(coll)'] < 0.2 else 'NOT fully on'}) |")
sw = run("fault_legs_swapped.cir")
print(f"| Transistor in backwards | {-sw['i(v5)']*1e3:.1f} mA through the LED | Light is dim or dark; nothing is damaged | Check the leg diagram |")
print(f"| Microphone VDD on 5 V instead of 3V3 | 5 V against a {MIC_VDD_MAX} V limit | **Microphone destroyed** | It is in the wiring table and the lesson |")
print(f"| 5 V rail shorted to ground | up to {CHARGER_A:.0f} A or more from the charger, against {CONTACT_MAX_A:.0f} A contacts | "
      f"**Wires and contacts heat up** until the charger cuts out | Unplug USB before moving any wire; use a certified charger |")
print("| A GPIO output shorted to ground | the pin limits itself to about 40 mA | Usually survives briefly | Unplug before rewiring |")
print("| Speaker output wire touches ground | the amplifier has short-circuit protection | Amp shuts down, recovers | Never ground either speaker wire |")
